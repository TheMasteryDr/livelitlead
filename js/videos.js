const STORAGE_KEY = "live_lit_lead_videos_v3";

/**
 * Extracts a YouTube Video ID from any YouTube URL format.
 */
function extractYouTubeId(url) {
  if (!url) return null;
  const cleanUrl = url.trim();

  // If already an 11-char ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(cleanUrl)) {
    return cleanUrl;
  }

  // Regex patterns for youtu.be, youtube.com/watch, youtube.com/embed, youtube.com/shorts, live
  const patterns = [
    /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|shorts\/|live\/))([a-zA-Z0-9_-]{11})/,
    /[?&]v=([a-zA-Z0-9_-]{11})/
  ];

  for (const pattern of patterns) {
    const match = cleanUrl.match(pattern);
    if (match && match[1]) {
      return match[1];
    }
  }

  return null;
}

/**
 * Gets high-resolution thumbnail URL for a YouTube ID
 */
function getYouTubeThumbnail(youtubeId) {
  return `https://img.youtube.com/vi/${youtubeId}/hqdefault.jpg`;
}

/**
 * Retrieves all videos (default + custom stored in localStorage)
 */
function getAllVideos() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn("Could not load from localStorage, using default videos:", e);
  }
  return DEFAULT_VIDEOS;
}

/**
 * Saves a new video into localStorage (Admin feature)
 */
function saveVideo(videoData) {
  const current = getAllVideos();
  const newVideo = {
    id: "lll-custom-" + Date.now(),
    youtubeId: videoData.youtubeId,
    title: videoData.title || "Weekly Teaching",
    pillar: videoData.pillar || "live-lit",
    pillarLabel: videoData.pillar === "build-lit" ? "Build Lit" : videoData.pillar === "lead-lit" ? "Lead Lit" : "Live Lit",
    pillarColor: videoData.pillar === "build-lit" ? "#FF7A30" : videoData.pillar === "lead-lit" ? "#FFA000" : "#E8501E",
    series: videoData.series || "Live Lit Lead Teachings",
    seriesEp: videoData.seriesEp || "Special Release",
    duration: videoData.duration || "25:00",
    date: videoData.date || new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" }),
    scripture: videoData.scripture || "Word of the Lord",
    description: videoData.description || "Weekly spiritual teaching from Live Lit Lead to help you grow spiritually.",
    takeaways: videoData.takeaways && videoData.takeaways.length ? videoData.takeaways : [
      "Keep the spiritual fire burning daily.",
      "Stay grounded in biblical truth and sound doctrine.",
      "Be bold and lead your sphere of influence."
    ],
    scripturesList: videoData.scripturesList && videoData.scripturesList.length ? videoData.scripturesList : [
      { ref: videoData.scripture || "Matthew 5:14", text: "You are the light of the world. A city that is set on an hill cannot be hid." }
    ],
    challenge: videoData.challenge || "Put this teaching into practice by sharing it with someone this week.",
    featured: false,
    views: "New",
    custom: true
  };

  const updated = [newVideo, ...current];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error("Failed to save to localStorage:", e);
  }
  return newVideo;
}

/**
 * Deletes a custom video
 */
function deleteVideo(id) {
  const current = getAllVideos();
  const updated = current.filter(v => v.id !== id);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error("Failed to delete video:", e);
  }
  return updated;
}

/**
 * Resets videos back to default list
 */
function resetVideos() {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch (e) {
    console.error("Failed to reset localStorage:", e);
  }
  return DEFAULT_VIDEOS;
}

